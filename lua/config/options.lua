-- Editor options (migrated from init.nvim, step-by-step confirmed)

local opt = vim.opt

-- =============================================================================
-- 行号与光标
-- =============================================================================

opt.number = true -- 显示绝对行号
opt.relativenumber = true -- 显示相对行号
opt.cursorline = true -- 高亮当前行
opt.scrolloff = 5 -- 光标距屏幕上下边缘至少保留 5 行
opt.signcolumn = "yes" -- 左侧预留符号列（诊断、断点等）

-- =============================================================================
-- 缩进与 Tab
-- =============================================================================

opt.tabstop = 4 -- Tab 字符显示宽度为 4
opt.shiftwidth = 4 -- 缩进宽度为 4 个空格
opt.expandtab = true -- 按 Tab 插入空格而非 Tab 字符
opt.smartindent = true -- 换行时按上一行智能缩进

-- =============================================================================
-- 窗口与布局
-- =============================================================================

opt.wrap = true -- 长行自动换行显示
opt.laststatus = 2 -- 始终显示状态栏（与旧 airline 配置一致）
opt.splitbelow = true -- 水平分屏时新窗口在下方
opt.splitright = true -- 垂直分屏时新窗口在右侧
opt.wildmenu = true -- 命令行补全时显示候选菜单（内置，无需插件）
opt.colorcolumn = "80" -- 在第 80 列显示参考竖线

-- =============================================================================
-- 折叠（nvim-ufo）
-- =============================================================================

opt.foldcolumn = "1" -- 左侧显示折叠列
opt.foldlevel = 99 -- 默认折叠深度（几乎全展开）
opt.foldlevelstart = 99 -- 打开文件时全展开
opt.foldenable = true -- 启用折叠
opt.foldmethod = "expr" -- foldexpr 由 nvim-ufo 注入

-- =============================================================================
-- 搜索
-- =============================================================================

opt.ignorecase = true -- 搜索时默认忽略大小写
opt.smartcase = true -- 搜索串含大写时改为区分大小写

-- =============================================================================
-- 性能与响应
-- =============================================================================

opt.updatetime = 300 -- 停止输入 300ms 后触发 CursorHold 等事件
opt.timeoutlen = 300 -- 多键映射等待时间（毫秒）
opt.ttimeoutlen = 150 -- 终端按键序列超时（毫秒）

-- =============================================================================
-- 补全（nvim-cmp）
-- =============================================================================

opt.completeopt = "menu,menuone,noselect" -- 补全菜单由 cmp 控制
vim.opt.shortmess:append("c") -- 隐藏补全菜单消息（原 coc 配置）

-- =============================================================================
-- 终端与颜色
-- =============================================================================

vim.env.NVIM_TUI_ENABLE_TRUE_COLOR = "1" -- 启用 Neovim TUI 真彩色
opt.termguicolors = true -- 终端使用 24bit 真彩色（含 tmux 内）

opt.guicursor = "n-v-c:block-Cursor" -- 普通/可视/命令模式使用块状光标

-- =============================================================================
-- 文件类型与语法
-- =============================================================================

vim.cmd.filetype("plugin", "on") -- 按文件类型加载 Neovim 内置 ftplugin
-- 语法高亮由 autocmds 按 buffer 启用：有 parser 用 treesitter，否则 fallback 到 syntax

-- =============================================================================
-- Leader
-- =============================================================================

vim.g.mapleader = " " -- Leader 键为空格

-- =============================================================================
-- 高亮
-- =============================================================================

vim.api.nvim_set_hl(0, "ColorColumn", { bg = "#3b3b3b" }) -- 参考列背景色
